/**
 * Lightweight world geography for the interactive global-presence map.
 *
 * Landmasses are stored as coarse [lng, lat] rings and rasterised at runtime
 * into a dot-matrix map. No map library, no tiles, no network requests 
 * just ~6KB of coordinates that render as a single SVG path.
 */

export type Ring = [number, number][];

/** Equirectangular canvas. 360° of longitude across, 145° of latitude down. */
export const MAP_W = 1000;
export const LAT_TOP = 84;
export const LAT_BOTTOM = -58;
export const MAP_H = Math.round((MAP_W * (LAT_TOP - LAT_BOTTOM)) / 360);

export const project = (lng: number, lat: number): [number, number] => [
 ((lng + 180) / 360) * MAP_W,
 ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * MAP_H,
];


/** Standard even-odd ray casting. */
function inRing(lng: number, lat: number, ring: Ring): boolean {
 let inside = false;
 for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
  const [xi, yi] = ring[i];
  const [xj, yj] = ring[j];
  if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
   inside = !inside;
  }
 }
 return inside;
}

export const isLand = (lng: number, lat: number) => LAND.some((r) => inRing(lng, lat, r));

/**
 * Rasterise the landmasses into one SVG path made of tiny circles, so the
 * whole map is a single DOM node instead of ~1,200 elements.
 */
export function buildDotPath(step = 3.1, r = 1.35): string {
 let d = '';
 for (let lat = LAT_TOP; lat >= LAT_BOTTOM; lat -= step) {
  for (let lng = -180; lng <= 180; lng += step) {
   if (!isLand(lng, lat)) continue;
   const [x, y] = project(lng, lat);
   d += `M${x.toFixed(1)} ${y.toFixed(1)}m${-r} 0a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 ${-r * 2} 0`;
  }
 }
 return d;
}

/** Quadratic arc between two projected points, bowed toward the top. */
export function arcPath(
 a: [number, number],
 b: [number, number],
 bow = 0.32,
): string {
 const [x1, y1] = project(a[0], a[1]);
 const [x2, y2] = project(b[0], b[1]);
 const mx = (x1 + x2) / 2;
 const my = (y1 + y2) / 2;
 const dist = Math.hypot(x2 - x1, y2 - y1);
 return `M${x1} ${y1} Q${mx} ${my - dist * bow} ${x2} ${y2}`;
}
